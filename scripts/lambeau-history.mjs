// Generates src/lambeauHistory.js — every Packers home game at Lambeau Field from 2000 through
// the last COMPLETED season, with the estimated temperature at the kickoff hour. Run once a year
// after the season ends (node scripts/lambeau-history.mjs 2026), like og-card.py: finished
// seasons never change, so this is history baked once, not a data cron. The current season is
// read live by the page (src/coldLedger.js).
//
// Why baked: each season's schedule is a ~300 KB response and the page would need 27 of them
// (plus 27 weather reads) per reader to build the same list in the browser.
// Why 2000: ESPN's archive carries real kickoff times from 2000 on; 1999's are midnight
// placeholders, and a kickoff temperature needs a kickoff.
// Temperatures: Open-Meteo's historical archive (ERA5 reanalysis) at the stadium, interpolated to the
// kickoff minute — an ESTIMATE, not the official game-book reading (it lands within a degree
// or two on the ones checked: 2008 NFC title game -1°F, 2014 wild card 5°F).
import fs from 'node:fs'

const SITE = 'https://site.api.espn.com/apis/site/v2/sports/football/nfl'
const TEAM = '9'
const LAT = 44.5013, LON = -88.0622
const FIRST = 2000
const LAST = Number(process.argv[2])
if (!LAST || LAST < FIRST) { console.error('usage: node scripts/lambeau-history.mjs <last completed season>'); process.exit(1) }

const getJSON = async (url) => { const r = await fetch(url); if (!r.ok) throw new Error(`${r.status} ${url}`); return r.json() }
// The temperature AT kickoff: the two hourly readings around it, interpolated (a 5:30 kickoff
// sits halfway between the 5:00 and 6:00 values). Same rule as src/coldLedger.js kickoffTemp().
function kickoffTemp(hourly, iso) {
  const d = new Date(iso)
  const key = (x) => x.toISOString().slice(0, 13) + ':00'
  const i = hourly.time.indexOf(key(d))
  const a = hourly.temperature_2m[i], b = hourly.temperature_2m[i + 1]
  if (i === -1 || a == null) return null
  const f = d.getUTCMinutes() / 60
  return f && b != null ? a + (b - a) * f : a
}

const games = []
for (let season = FIRST; season <= LAST; season++) {
  const rows = []
  for (const type of [2, 3]) {
    let data
    try { data = await getJSON(`${SITE}/teams/${TEAM}/schedule?season=${season}&seasontype=${type}`) } catch { if (type === 2) throw new Error(`no regular season for ${season}`); continue }
    for (const e of data.events || []) {
      const c = e.competitions[0]
      const me = c.competitors.find((x) => x.team.id === TEAM)
      const opp = c.competitors.find((x) => x.team.id !== TEAM)
      if (!me || me.homeAway !== 'home' || c.neutralSite || !c.status?.type?.completed) continue
      // The Packers have played every true home game at Lambeau since 1995; the venue field is
      // empty before 2006, so only a NAMED other stadium disqualifies a game.
      if (c.venue?.fullName && c.venue.fullName !== 'Lambeau Field') continue
      const hour = new Date(e.date).getUTCHours()
      if (new Date(e.date).getUTCMinutes() === 0 && hour >= 4 && hour <= 6) throw new Error(`placeholder kickoff time: ${season} ${e.date}`)
      rows.push({ date: e.date, opp: Number(opp.team.id), gb: me.score?.value, them: opp.score?.value, post: type === 3 ? 1 : 0 })
    }
  }
  if (!rows.length) throw new Error(`no home games found for ${season}`)
  // One weather read per season: September through mid-February covers the playoffs.
  const w = await getJSON(`https://archive-api.open-meteo.com/v1/archive?latitude=${LAT}&longitude=${LON}&start_date=${season}-09-01&end_date=${season + 1}-02-15&hourly=temperature_2m&temperature_unit=fahrenheit&timezone=GMT`)
  for (const r of rows) {
    const t = kickoffTemp(w.hourly, r.date)
    if (t == null || r.gb == null || r.them == null) throw new Error(`incomplete row: ${season} ${r.date}`)
    games.push([r.date, r.opp, r.gb, r.them, Math.round(t), r.post])
  }
  console.log(season, rows.length, 'games')
}
games.sort((a, b) => new Date(a[0]) - new Date(b[0]))

const out = `// GENERATED by scripts/lambeau-history.mjs — do not edit by hand. Every Packers home game at
// Lambeau Field, ${FIRST}–${LAST} seasons (regular season + playoffs), with the estimated temperature at
// the kickoff hour (Open-Meteo's historical archive; an estimate, not the game-book reading).
// Finished seasons never change: rerun the script once a year, after the season, with the new
// last season — the page reads the season in progress live (src/coldLedger.js).
export const HISTORY_FROM = ${FIRST}
export const HISTORY_THROUGH = ${LAST}
// [kickoff ISO (UTC), opponent team id, Packers score, opponent score, °F at kickoff, playoffs 0|1]
export const LAMBEAU_GAMES = [
${games.map((g) => `  ${JSON.stringify(g)},`).join('\n')}
]
`
fs.writeFileSync(new URL('../src/lambeauHistory.js', import.meta.url), out)
console.log(`wrote ${games.length} games`)
// A look at the result, for the person running it.
const hours = {}
games.forEach((g) => { const h = new Date(g[0]).toLocaleString('en-US', { timeZone: 'America/Chicago', hour: 'numeric' }); hours[h] = (hours[h] || 0) + 1 })
console.log('kickoff hours (CT):', hours)
console.log('coldest:', [...games].sort((a, b) => a[4] - b[4]).slice(0, 12).map((g) => `${g[4]}°F ${g[0].slice(0, 10)} vs ${g[1]} ${g[2]}-${g[3]}`))
